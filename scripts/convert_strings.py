#!/usr/bin/env python3
"""Turns an Android app's strings.xml (every language under res/values*) into iOS
Localizable.strings, Localizable.stringsdict and InfoPlist.strings, so both apps say the same thing.

    python3 convert_strings.py <android>/app/src/main/res App/Resources [ios-strings.json]

Keys stay the Android names. "%1$s" becomes "%1$@", "%d" becomes "%ld". Plurals become
"name#one", "name#other"... entries in Localizable.strings (all six CLDR forms, so Arabic works);
the app picks the form for the count itself and formats it with Android's arguments, so plurals
with a second argument ("%1$d of %2$d items") work as on Android. values/ is English ("en"); values-xx/
becomes xx.lproj. The optional JSON holds what only iOS says:

    {"overrides": {"en": {"key": "iOS wording"}, "ar": {...}},   # replaces Android texts (Play → App Store...)
     "extra":     {"en": {"new_key": "..."}},                     # strings only the iOS app has
     "infoplist": {"en": {"CFBundleDisplayName": "...", "NSCameraUsageDescription": "..."}}}

Run it again whenever the Android strings change; keep a copy of this script and the JSON in the repo.
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


def android_text(raw: str) -> str:
    """Android resource escapes to the plain text they stand for."""
    if raw is None:
        return ""
    s = raw.strip()
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        s = s[1:-1]
    out = []
    i = 0
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "n":
                out.append("\n"); i += 2; continue
            if n == "t":
                out.append("\t"); i += 2; continue
            if n == "u" and i + 5 < len(s):
                out.append(chr(int(s[i + 2:i + 6], 16))); i += 6; continue
            out.append(n); i += 2; continue
        out.append(ch)
        i += 1
    return "".join(out)


def ios_format(s: str) -> str:
    s = re.sub(r"%(\d+\$)?s", lambda m: "%" + (m.group(1) or "") + "@", s)
    s = re.sub(r"%(\d+\$)?d", lambda m: "%" + (m.group(1) or "") + "ld", s)
    return s


def strings_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def xml_escape(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def inner_text(el) -> str:
    # Keeps text of any inline markup (<xliff:g> and the like).
    return "".join(el.itertext())


def languages(res: Path):
    for d in sorted(res.iterdir()):
        if (d / "strings.xml").exists():
            if d.name == "values":
                yield "en", d
            elif re.fullmatch(r"values-[a-z]{2,3}(-r[A-Z]{2})?", d.name):
                code = d.name[len("values-"):].replace("-r", "-")
                yield code, d


def convert(res: Path, out: Path, extras: dict):
    for lang, folder in languages(res):
        root = ET.parse(folder / "strings.xml").getroot()
        strings, plurals = {}, {}
        for el in root:
            name = el.get("name")
            if el.get("translatable") == "false" and lang != "en":
                continue
            if el.tag == "string":
                strings[name] = android_text(inner_text(el))
            elif el.tag == "plurals":
                plurals[name] = {item.get("quantity"): android_text(inner_text(item)) for item in el}
        strings.update(extras.get("overrides", {}).get(lang, {}))
        strings.update(extras.get("extra", {}).get(lang, {}))

        d = out / f"{lang}.lproj"
        d.mkdir(parents=True, exist_ok=True)
        lines = ["/* Generated by convert_strings.py from the Android strings.xml. */", ""]
        for k in sorted(strings):
            lines.append(f'"{k}" = "{strings_escape(ios_format(strings[k]))}";')
        lines += ["", "/* Plurals: one entry per CLDR form, picked by P() in Strings.swift. */", ""]
        for k in sorted(plurals):
            for q in ("zero", "one", "two", "few", "many", "other"):
                if q in plurals[k]:
                    lines.append(f'"{k}#{q}" = "{strings_escape(ios_format(plurals[k][q]))}";')
        (d / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")

        info = extras.get("infoplist", {}).get(lang, {})
        if info:
            lines = ["/* Generated by convert_strings.py. */", ""] + [f'"{k}" = "{strings_escape(v)}";' for k, v in info.items()]
            (d / "InfoPlist.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{lang}: {len(strings)} strings, {len(plurals)} plurals")


if __name__ == "__main__":
    extras = json.load(open(sys.argv[3], encoding="utf-8")) if len(sys.argv) > 3 else {}
    convert(Path(sys.argv[1]), Path(sys.argv[2]), extras)
